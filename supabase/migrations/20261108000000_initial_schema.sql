create table if not exists public.products (
  id text primary key,
  current_price numeric not null check (current_price >= 0),
  currency text not null default 'HKD',
  last_checked_at timestamptz
);

create table if not exists public.price_alerts (
  id bigint generated by default as identity primary key,
  product_id text not null,
  email text,
  target_price_hkd numeric not null check (target_price_hkd >= 0),
  currency text not null default 'HKD',
  created_at timestamptz not null default now()
);

create table if not exists public.wishlists (
  user_id uuid not null references auth.users(id) on delete cascade,
  product_id text not null,
  created_at timestamptz not null default now(),
  primary key (user_id, product_id)
);

create index if not exists price_alerts_product_id_idx
  on public.price_alerts (product_id);

alter table public.products enable row level security;
alter table public.price_alerts enable row level security;
alter table public.wishlists enable row level security;

create policy "Public products are readable"
  on public.products for select using (true);

create policy "Anyone can create price alerts"
  on public.price_alerts for insert with check (true);

create policy "Users can view their wishlists"
  on public.wishlists for select using (auth.uid() = user_id);

create policy "Users can add to their wishlists"
  on public.wishlists for insert with check (auth.uid() = user_id);

create policy "Users can remove from their wishlists"
  on public.wishlists for delete using (auth.uid() = user_id);
